"""Generates the menu header's pictures, as layered SVGs: each <path data-tone="…"> is one flat
tone, in painting order. The materials and their top-left shading follow the approved pixel-art
design ("B1"); the shapes are the line drawings, flattened into straight segments.

    python tools/header_art.py            (needs: pip install shapely svgpathtools)

Inputs (tools/): airpods_pro_drawing.svg ("Airpods Pro" by Alex Martynov, SVG Repo #324521, CC
Attribution): the two buds; airpods_case_closed.svg and airpods_case_open.svg (drawn for QuickTooth
by airpods_case.py): the case. Outputs (assets/): header-bud-left.svg, header-bud-right.svg,
header-case-closed.svg, header-case-open-back.svg, header-case-open-front.svg (the open case in
two, so seated buds go between). All in the 128-unit drawing box.
"""
import os
import re
import sys
from shapely import affinity
from shapely.geometry import MultiPolygon, Polygon, box
from shapely.ops import unary_union
from svgpathtools import Line, parse_path

FLAT_STEP = 0.4   # drawing units: the longest straight segment a curve becomes
SIMPLIFY = 0.04   # drawing units: points that bend an outline less than this go
LIGHT = (1.0, 1.0)  # the light comes from the top left: shade bands lie toward the bottom right

TOOLS = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(TOOLS, "..", "assets")


def rings(d):
    out = []
    for sub in parse_path(d).continuous_subpaths():
        pts = []
        for seg in sub:
            n = 1 if isinstance(seg, Line) else max(2, int(seg.length() / FLAT_STEP) + 1)
            for k in range(n):
                p = seg.point(k / n)
                pts.append((p.real, p.imag))
        if len(pts) >= 3:
            out.append(pts)
    return out


def evenodd(d):
    g = Polygon()
    for r in rings(d):
        g = g.symmetric_difference(Polygon(r).buffer(0))
    return g.buffer(0)


def polys(g):
    if g.is_empty:
        return []
    if isinstance(g, Polygon):
        return [g]
    return [p for p in getattr(g, "geoms", []) if isinstance(p, Polygon)]


def holes(g):
    return [Polygon(h) for p in polys(g) for h in p.interiors]


def silhouette(g):
    return unary_union([Polygon(p.exterior) for p in polys(g)]).buffer(0)


def band(region, k, toward=+1):
    """The part of `region` within k of its edge facing the light (toward=-1) or away (+1)."""
    moved = affinity.translate(region, -toward * k * LIGHT[0], -toward * k * LIGHT[1])
    return region.difference(moved).buffer(0)


class Art:
    def __init__(self):
        self.layers = []

    def add(self, tone, g):
        g = g.buffer(0).simplify(SIMPLIFY)
        if not g.is_empty:
            self.layers.append((tone, g))

    def material(self, region, base, hi, lo, lo2=None, k=(1.6, 5.0, 2.2)):
        """A region in its base tone, lit along the top-left edge, shaded along the bottom right."""
        self.add(base, region)
        self.add(hi, band(region, k[0], -1))
        self.add(lo, band(region, k[1], +1))
        if lo2:
            self.add(lo2, band(region, k[2], +1))

    def lines(self, lines, sil):
        """Slate lines; darker where they're on the underside."""
        under = band(sil, 2.5, +1).buffer(0.8)
        self.add("line", lines.difference(under))
        self.add("line-under", lines.intersection(under))

    def svg(self, note):
        parts = []
        for tone, g in self.layers:
            d = []
            for p in polys(g):
                p = p.__class__(p.exterior, p.interiors)
                from shapely.geometry.polygon import orient
                p = orient(p, 1.0)
                for r in [p.exterior, *p.interiors]:
                    d.append("M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in list(r.coords)[:-1]) + "Z")
            parts.append(f'<path data-tone="{tone}" d="{"".join(d)}"/>')
        return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128">'
                f'<!-- Generated by tools/header_art.py from {note}. Don\'t edit. -->' + "".join(parts) + "</svg>\n")


def shadow(art, sil, depth=2.2):
    """A soft ground shadow: a flat band under the shape's lowest part."""
    minx, miny, maxx, maxy = sil.bounds
    foot = sil.intersection(box(minx - 1, maxy - 8, maxx + 1, maxy + 1))
    if foot.is_empty:
        return
    fx0, _, fx1, _ = foot.bounds
    w = (fx1 - fx0) * 0.5 + 3
    cx = (fx0 + fx1) / 2
    from shapely.geometry import Point
    ell = affinity.scale(Point(cx, maxy + depth).buffer(1, 64), w, depth)
    art.add("shadow", ell)


def bud(lines):
    sil = silhouette(lines)
    hs = sorted(holes(lines), key=lambda h: -h.area)
    head, tip, stem, mesh, vent_out, vent_in = hs[:6]
    art = Art()
    shadow(art, sil)
    art.material(head, "shell", "shell-hi", "shell-lo", "shell-lo2")
    sx0, sy0, sx1, sy1 = stem.bounds
    cap = stem.intersection(box(sx0 - 1, sy1 - (sy1 - sy0) * 0.13, sx1 + 1, sy1 + 1))
    art.material(stem.difference(cap), "shell", "shell-hi", "shell-lo", "shell-lo2")
    art.material(cap, "cap", "cap", "cap-lo")
    art.material(tip, "tip", "tip-hi", "tip-lo", "tip-lo2")
    art.add("mesh", mesh)
    art.add("vent", vent_out)
    art.add("vent-in", vent_in)
    art.lines(lines, sil)
    return art


def case_regions(path):
    text = open(path, encoding="utf-8").read()
    named = dict(re.findall(r'<path id="([^"]+)"[^>]*\sd="([^"]+)"', text))
    if not named:
        named = {"all": d for d in re.findall(r'<path[^>]*\sd="([^"]+)"', text)}
    return {k: evenodd(v) for k, v in named.items()}


def by_area(lines):
    return sorted(holes(lines), key=lambda h: -h.area)


def main():
    drawing = open(os.path.join(TOOLS, "airpods_pro_drawing.svg"), encoding="utf-8").read()
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', drawing)
    assert len(paths) == 16, len(paths)
    src = '"Airpods Pro" by Alex Martynov (SVG Repo #324521, CC Attribution)'
    out = {}
    for side, ds in (("left", paths[:8]), ("right", paths[8:])):
        out[f"header-bud-{side}.svg"] = bud(unary_union([evenodd(d) for d in ds]).buffer(0)).svg(src)

    case_src = "tools/airpods_case_*.svg"
    closed = case_regions(os.path.join(TOOLS, "airpods_case_closed.svg"))
    lines = unary_union(list(closed.values())).buffer(0)
    sil = silhouette(lines)
    body, lid, led = by_area(lines)[:3]
    art = Art()
    shadow(art, sil, 3.0)
    art.material(body, "shell", "shell-hi", "shell-lo", "shell-lo2", k=(2.0, 9.0, 3.5))
    art.material(lid, "shell", "shell-hi", "shell-lo", None, k=(2.0, 5.0, 2.0))
    art.add("led", led.buffer(1.4))
    art.lines(lines, sil)
    out["header-case-closed.svg"] = art.svg(case_src)

    opened = case_regions(os.path.join(TOOLS, "airpods_case_open.svg"))
    back_lines = unary_union([g for k, g in opened.items() if k.startswith("back")]).buffer(0)
    front_lines = unary_union([g for k, g in opened.items() if k.startswith("front")]).buffer(0)
    lines = unary_union([back_lines, front_lines]).buffer(0)
    sil = silhouette(lines)
    hs = by_area(lines)
    body, lid_face, mouth, hinge, lid_rim, led = hs[:6]
    back = Art()
    shadow(back, sil, 3.0)
    back.add("shell", sil.difference(body))
    back.material(lid_face, "lid", "lid-hi", "lid-lo", None, k=(2.0, 6.0, 2.0))
    back.material(lid_rim, "shell", "shell-hi", "shell-lo")
    back.add("hinge", hinge)
    back.add("mouth", mouth)
    back.add("well", mouth.buffer(-2.2))
    back.lines(back_lines.difference(body.buffer(0.6)), sil)
    out["header-case-open-back.svg"] = back.svg(case_src)
    front = Art()
    front.material(body, "shell", "shell-hi", "shell-lo", "shell-lo2", k=(2.0, 9.0, 3.5))
    front.add("led", led.buffer(1.4))
    front.lines(lines.intersection(body.buffer(1.4)).union(front_lines).buffer(0), sil)
    out["header-case-open-front.svg"] = front.svg(case_src)

    for name, text in out.items():
        path = os.path.join(OUT, name)
        open(path, "w", encoding="utf-8", newline="\n").write(text)
        print(f"{name}: {len(text)} bytes")


if __name__ == "__main__":
    if len(sys.argv) > 1:
        OUT = sys.argv[1]
    main()
