"""Generates assets/airpods-pro-art-left.svg and assets/airpods-pro-art-right.svg: the menu header's
earbuds, the original line drawing at full detail.

    python tools/airpods_art.py            (needs: pip install shapely svgpathtools)

Source: tools/airpods_pro_drawing.svg, "Airpods Pro" by Alex Martynov, SVG Repo #324521
(www.svgrepo.com/svg/324521), CC Attribution. Its 16 paths are filled outlines with even-odd holes:
the first 8 draw the left bud, the rest the right one. Every curve is flattened into straight
segments at most FLAT_STEP long (the renderer takes only M/L/Z) and each bud becomes one shape,
oriented so the renderer's nonzero fill keeps the holes. Units stay the drawing's (128 × 128).
"""
import os
import re
from svgpathtools import Line, parse_path
from shapely.geometry import MultiPolygon, Polygon
from shapely.geometry.polygon import orient
from shapely.ops import unary_union

FLAT_STEP = 0.4   # drawing units; a quarter of a pixel at the header's size
SIMPLIFY = 0.04   # drawing units: drops points that bend the outline less than this
HERE = os.path.dirname(os.path.abspath(__file__))


def rings(d):
    """The closed sub-paths of a path, flattened."""
    out = []
    for sub in parse_path(d).continuous_subpaths():
        pts = []
        for seg in sub:
            n = 1 if isinstance(seg, Line) else max(2, int(seg.length() / FLAT_STEP) + 1)
            for k in range(n):
                p = seg.point(k / n)
                pts.append((p.real, p.imag))
        if len(pts) >= 3:
            out.append(pts)
    return out


def shape(d):
    """One path, even-odd: each sub-path toggles what it covers."""
    geom = Polygon()
    for r in rings(d):
        geom = geom.symmetric_difference(Polygon(r).buffer(0))
    return geom


def svg(geom):
    polys = geom.geoms if isinstance(geom, MultiPolygon) else [geom]
    parts = []
    for p in polys:
        p = orient(p, 1.0)  # exterior one way, holes the other: nonzero keeps the holes
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)[:-1]
            parts.append("M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in c) + "Z")
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128">'
            '<!-- Generated by tools/airpods_art.py from "Airpods Pro" by Alex Martynov (SVG Repo #324521, '
            'CC Attribution). Don\'t edit. -->'
            f'<path fill="#000" d="{"".join(parts)}"/></svg>\n')


def main():
    text = open(os.path.join(HERE, "airpods_pro_drawing.svg"), encoding="utf-8").read()
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', text)
    assert len(paths) == 16, len(paths)
    for side, ds in (("left", paths[:8]), ("right", paths[8:])):
        geom = unary_union([shape(d) for d in ds]).buffer(0).simplify(SIMPLIFY)
        out = os.path.join(HERE, "..", "assets", f"airpods-pro-art-{side}.svg")
        open(out, "w", encoding="utf-8", newline="\n").write(svg(geom))
        print(f"{out}: {os.path.getsize(out)} bytes, bounds {tuple(round(v, 2) for v in geom.bounds)}")


if __name__ == "__main__":
    main()
