//! PocketKnives.Settings.exe: the runner's Windows 11 settings window, a WinUI 3 app in `no_std`
//! Rust (a feasibility spike for moving it off C#; docs/specs/runner.md has what it shows).
//!
//! It takes one argument, the runner's window handle, and runs the WinUI app from the
//! self-contained Windows App SDK runtime next to it (`stage.ps1` lays it out).
//!
//! - [`app`]: the WinUI `Application` subclass, by COM aggregation.
//! - [`ui`]: the window and its pages. [`boxed`]: a delegate boxed for `AddHandler`.
//! - [`stub`]: stand-ins for the runner's settings code (ported separately).
//! - `bindings`: the WinUI bindings generated by `gen/` from the Windows App SDK winmds.
//!
//! Exit codes: 0 the window closed; 2 bad arguments; 3 the Windows App SDK runtime is missing or
//! failed to load; 4 WinUI failed to start or to open the window. `pk.exe` opens the Windows 10
//! look on any non-zero code.
#![no_std]
#![no_main]

extern crate alloc;

mod app;
#[allow(clippy::all, dead_code, non_camel_case_types, non_snake_case, non_upper_case_globals)]
#[rustfmt::skip]
mod bindings;
mod boxed;
mod stub;
mod ui;

use core::sync::atomic::{AtomicIsize, AtomicU32, Ordering};
use pk::wide::to_wide;
use windows_sys::Win32::System::Com::{COINIT_APARTMENTTHREADED, CoInitializeEx};
use windows_sys::Win32::System::Environment::SetEnvironmentVariableW;
use windows_sys::Win32::System::LibraryLoader::{GetProcAddress, LoadLibraryW};
use windows_sys::Win32::System::Threading::GetCurrentProcessId;

pub const EXIT_ARGS: u32 = 2;
pub const EXIT_RUNTIME: u32 = 3;
pub const EXIT_WINUI: u32 = 4;

/// The runner's window. The real app posts it a message to reopen Settings in another look; the
/// spike never does.
static RUNNER: AtomicIsize = AtomicIsize::new(0);
/// Set when WinUI started but the window could not open: `Application.Start` still returns.
static FAILED: AtomicU32 = AtomicU32::new(0);

pk::entry!(main);

fn main() -> u32 {
    let args = pk::args::args();
    let [arg] = args.as_slice() else { return EXIT_ARGS };
    let runner = match arg.trim().parse::<isize>() {
        Ok(0) | Err(_) => return EXIT_ARGS,
        Ok(h) => h,
    };
    RUNNER.store(runner, Ordering::Relaxed);
    if !load_runtime() {
        return EXIT_RUNTIME;
    }
    unsafe { CoInitializeEx(core::ptr::null(), COINIT_APARTMENTTHREADED as u32) };
    let callback = bindings::Microsoft::UI::Xaml::ApplicationInitializationCallback::new(|_| {
        app::create().inspect_err(|e| report("Application could not be created", e))
    });
    if let Err(e) = bindings::Microsoft::UI::Xaml::Application::Start(&callback) {
        report("Application.Start failed", &e);
        return EXIT_WINUI;
    }
    FAILED.load(Ordering::Relaxed)
}

/// Records that the window could not open and ends the app: `Start` then returns.
pub fn fail(code: u32) {
    FAILED.store(code, Ordering::Relaxed);
    pk::exit(code);
}

/// Prints why WinUI failed, when stdout goes somewhere (a pipe or a file): one line.
pub fn report(what: &str, e: &windows_core::Error) {
    let mut out = pk::out::Writer::new(pk::out::stdout_handle());
    if !out.is_null() {
        let line = alloc::format!("{what}: 0x{:08X} {}
", e.code().0, e.message());
        out.write_bytes(line.as_bytes());
    }
}

pub fn runner_window() -> isize {
    RUNNER.load(Ordering::Relaxed)
}

/// What the Windows App SDK's self-contained auto-initializer does before `Main` in the C# app
/// (UndockedRegFreeWinRT-AutoInitializer.cs): tell the runtime where it is, then load it. Loaded
/// by full path, not imported, so a missing runtime is exit code 3 rather than a loader error box.
fn load_runtime() -> bool {
    let mut dir = pk::env::exe_dir();
    dir.push('\\');
    let pid = alloc::format!("{}", unsafe { GetCurrentProcessId() });
    unsafe {
        SetEnvironmentVariableW(to_wide("MICROSOFT_WINDOWSAPPRUNTIME_BASE_DIRECTORY").as_ptr(), to_wide(&dir).as_ptr());
        SetEnvironmentVariableW(to_wide("MICROSOFT_WINDOWSAPPRUNTIME_BASE_DIRECTORY_PID").as_ptr(), to_wide(&pid).as_ptr());
    }
    dir.push_str("Microsoft.WindowsAppRuntime.dll");
    let dll = unsafe { LoadLibraryW(to_wide(&dir).as_ptr()) };
    if dll.is_null() {
        return false;
    }
    let Some(ensure) = (unsafe { GetProcAddress(dll, c"WindowsAppRuntime_EnsureIsLoaded".as_ptr().cast()) }) else {
        return false;
    };
    // STDAPI WindowsAppRuntime_EnsureIsLoaded(): an HRESULT.
    let ensure: unsafe extern "system" fn() -> i32 = unsafe { core::mem::transmute(ensure) };
    unsafe { ensure() >= 0 }
}
